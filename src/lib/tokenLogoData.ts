function normalizeLogoSymbol(
  value: unknown,
): string {
  return String(
    value || "",
  )
    .trim()
    .toUpperCase();
}

export function getOfficialTokenLogoCandidates(
  displayValue: unknown,
  sourceCoin?: unknown,
): string[] {
  const base =
    normalizeLogoSymbol(
      displayValue,
    );

  const exactSourceCoin =
    String(
      sourceCoin || "",
    ).trim();

  const urls: string[] = [];

  const pushUrl = (
    url: string,
  ) => {
    const value =
      String(
        url || "",
      ).trim();

    if (
      value &&
      !urls.includes(value)
    ) {
      urls.push(value);
    }
  };

  const hasDexPrefix =
    exactSourceCoin.includes(
      ":",
    );

  const dexParts =
    hasDexPrefix
      ? exactSourceCoin.split(
          ":",
          2,
        )
      : [];

  const dexLabel =
    String(
      dexParts[0] || "",
    ).trim();

  const dexDisplayName =
    String(
      dexParts[1] || "",
    ).trim();

  /*
   * HIP-3 / SUB-DEX:
   *
   * #1 exact Hyperliquid official sourceCoin SVG.
   */
  if (
    hasDexPrefix &&
    exactSourceCoin
  ) {
    pushUrl(
      `https://app.hyperliquid.xyz/coins/${exactSourceCoin}.svg`,
    );

    /*
     * #2 Authorized SECONDARY source.
     *
     * xyz:ARM -> xyzARM.png
     * para:AVGO -> paraAVGO.png
     */
    if (
      dexLabel &&
      dexDisplayName
    ) {
      pushUrl(
        `https://uni.onekey-asset.com/static/hyperliquid/${dexLabel}${dexDisplayName}.png`,
      );
    }

    /*
     * #3 Verified static logo fallback for HIP-3 assets.
     */
    const hip3StaticKey = (
      dexDisplayName || base
    ).toUpperCase();

    const knownHip3Url =
      REAL_TOKEN_LOGO_URLS[
        hip3StaticKey
      ];

    if (knownHip3Url) {
      pushUrl(knownHip3Url);
    }

    const hip3Aliases =
      OFFICIAL_LOGO_SYMBOL_CANDIDATES[
        hip3StaticKey
      ] || [];

    for (const alias of hip3Aliases) {
      const aliasUpper = String(alias || "").trim().toUpperCase();
      const aliasUrl = REAL_TOKEN_LOGO_URLS[aliasUpper];
      if (aliasUrl) {
        pushUrl(aliasUrl);
      }
    }

    /*
     * IMPORTANT:
     *
     * Do NOT fall through to arbitrary bare-symbol remote logos.
     *
     * Same ticker can represent a different asset on another DEX.
     *
     * Existing local fallback is safer than a WRONG logo.
     */
    return urls;
  }

  /*
   * NATIVE / NORMAL:
   *
   * TASK 7 — Exact native sourceCoin must be first
   * (e.g. sourceCoin = kSHIB -> kSHIB.svg then kSHIB.png)
   */
  // Venue-qualified quote pairs like Aster BTCUSDT and ETHUSDT are NOT
  // Hyperliquid token identity keys. Skip futile BTCUSDT.svg lookups, then
  // use the existing verified BASE identity logo and its normal fallbacks.
  const quotedMarketPair = Boolean(
    base &&
    (exactSourceCoin.toUpperCase() === base + "USDT" ||
     exactSourceCoin.toUpperCase() === base + "USDC")
  );
  if (
    exactSourceCoin &&
    !exactSourceCoin.startsWith("@") &&
    !quotedMarketPair
  ) {
    pushUrl(
      `https://app.hyperliquid.xyz/coins/${exactSourceCoin}.svg`,
    );

    pushUrl(
      `https://uni.onekey-asset.com/static/hyperliquid/${exactSourceCoin}.png`,
    );
  }

  if (!base) {
    return urls;
  }

  /*
   * existing verified static URL
   */
  const knownUrl =
    REAL_TOKEN_LOGO_URLS[
      base
    ];

  if (knownUrl) {
    pushUrl(
      knownUrl,
    );
  }

  /*
   * existing VERIFIED aliases
   */
  const candidateSymbols =
    OFFICIAL_LOGO_SYMBOL_CANDIDATES[
      base
    ] || [];

  for (
    const candidate
    of candidateSymbols
  ) {
    const symbol =
      normalizeLogoSymbol(
        candidate,
      );

    if (!symbol) {
      continue;
    }

    const mappedUrl =
      REAL_TOKEN_LOGO_URLS[
        symbol
      ];

    if (mappedUrl) {
      pushUrl(mappedUrl);
    }
    // Official source image and small CDN fallback: never bundle binary logos.
    pushUrl(`https://app.hyperliquid.xyz/coins/${symbol}.svg`);
    pushUrl(`https://uni.onekey-asset.com/static/hyperliquid/${symbol}.png`);
  }

  /*
   * normal official SVG
   */
  pushUrl(
    `https://app.hyperliquid.xyz/coins/${base}.svg`,
  );

  /*
   * Authorized SECONDARY normal asset.
   */
  pushUrl(
    `https://uni.onekey-asset.com/static/hyperliquid/${base}.png`,
  );

  return urls;
}
